using ActualChat.Aot;
using ActualChat.Module;

namespace ActualChat.UI.Blazor.Module;

#pragma warning disable CA2255 // Module initializer is intended to be used in...

public static partial class BlazorUIModuleInitializer
{
    public static void Load() { }

    [ModuleInitializer]
    internal static void ModuleInitializer()
    {
        ApiContractsModuleInitializer.Load();
        AotTypes.AddSource(new BlazorUIAotSource());
        AotJsonContexts.Add(BlazorUIJsonContext.Default);
        KeepBlazorIpcTypes();
    }

    /// <summary>
    /// Manual keeps for types the STJ generator can't auto-discover.
    /// Most STJ converter keeps are now auto-generated into BlazorUIAotSource.g.cs.
    /// </summary>
    private static void KeepBlazorIpcTypes()
    {
        if (CodeKeeper.AlwaysTrue)
            return;

        CodeKeeper.Keep("Microsoft.JSInterop.JSRuntime, Microsoft.JSInterop");

        // Value types needing RuntimeHelpers.IsReferenceOrContainsReferences<T>
        CodeKeeper.Keep<JsonElement>();
        CodeKeeper.Keep<long>();
        CodeKeeper.Keep<float>();

        // ApiArrayJsonConverter builds per-T sub-converters through a parameterless
        // Expression<Func<Converter<T>>> factory. NativeAOT needs each concrete Converter<T>
        // and its Expression/Func generic instantiations kept explicitly for every T that
        // crosses JSON. The inner Converter<T> is internal so we use AQN-form keeps.
        // If new ApiArray<T> types appear in JS interop, add their triple here.
        CodeKeeper.Keep("ActualLab.Api.Internal.ApiArrayJsonConverter+Converter`1"
            + "[[ActualLab.Text.Symbol, ActualLab.Core]], ActualLab.Core");
        CodeKeeper.Keep("System.Func`1[[ActualLab.Api.Internal.ApiArrayJsonConverter+Converter`1"
            + "[[ActualLab.Text.Symbol, ActualLab.Core]], ActualLab.Core]], System.Private.CoreLib");
        CodeKeeper.Keep("System.Linq.Expressions.Expression`1[[System.Func`1"
            + "[[ActualLab.Api.Internal.ApiArrayJsonConverter+Converter`1"
            + "[[ActualLab.Text.Symbol, ActualLab.Core]], ActualLab.Core]], System.Private.CoreLib]]"
            + ", System.Linq.Expressions");

        // Note: CreateDefaultStateOptionsFactory<T> keeps are now auto-generated
        // by App.AotHelper -g (discovers all ComputedStateComponent<T> descendants).

#if false // Covered by STJ generator (auto-discovered into BlazorUIAotSource.g.cs)
        // All of the following were manually maintained but are now auto-generated by
        // App.AotHelper -g, which discovers JS interop root types and walks the STJ
        // converter graph to find all needed internal converter AQNs.
        //
        // Categories that are auto-generated:
        // - EnumConverter<T> for enums (SideNavSide, VirtualListEdge, Tune, JSCallResultType, JSCallType)
        // - ArrayConverter<T[], T> for arrays (JsonElement[], int[], Word[], WebFileInfo[], etc.)
        // - ObjectDefaultConverter<T> for POCOs (ElementReference, NavigationOptions, VoidTaskResult, Word, etc.)
        // - SmallObjectWithParameterizedConstructorConverter for records/structs (Range<T>, KVP<K,V>, VirtualListDataQuery)
        // - DictionaryOfTKeyTValueConverter + IDictionary + IReadOnlyDictionary (Tune/TuneInfo, string/bool)
        // - IEnumerableOfTConverter + ICollectionOfTConverter + IListOfTConverter (Symbol, Word, KVP collections)
        // - ListOfTConverter (Symbol)
        // - JsonPropertyInfo<T> for property metadata (Range variants, Tune)
        // - TaskResultGetter<VoidTaskResult> (JSInterop internal)
        // - JSRuntime, WindowsResourcesProvider (framework types)
#endif
    }
}
